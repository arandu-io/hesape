// The spellings of the generic model layer, in halves so this file does not
// carry them whole. That layer is gone, and an entity written against it does
// not compile -- but a comment that teaches it does, and the next entity is
// copied from what is here.
const (
	genericOpen      = "["
	genericModel     = "model.Model" + genericOpen
	genericBuilder   = "model.Builder" + genericOpen
	genericRows      = "model.Collection" + genericOpen
	genericFactory   = "Factory" + genericOpen
	genericNewModel  = "model.NewModel" + genericOpen
	genericInstance  = "NewInstance" + "("
	generatedHeading = "// Code generated by aru model:build" + " from model.go. DO NOT EDIT."
)

// TestThePackageUsesTheGeneratedConcreteModel freezes the shape of the data
// path: each entity embeds the non-generic Model, its table is declared once
// beside it, the query aru model:build generates is the one way in, the entity
// keeps a custom block for its own rules, the Service owns the database
// handle, and CRUD does not grow a Repository of its own.
func TestThePackageUsesTheGeneratedConcreteModel(t *testing.T) {
	t.Parallel()

	root := packageRoot(t)
	if _, err := os.Lstat(filepath.Join(root, "repository.go")); err == nil {
		t.Error("repository.go exists; CRUD belongs to the generated query")
	} else if !os.IsNotExist(err) {
		t.Fatalf("checking repository.go: %v", err)
	}

	wants := map[string][]string{
		"model.go": {
			`"github.com/arandu-io/hesape/database/model"`,
			"type Endpoint struct {\n\tmodel.Model\n",
			"type Call struct {\n\tmodel.Model\n",
			"type Delivery struct {\n\tmodel.Model\n",
			"type DeliveryAttempt struct {\n\tmodel.Model\n",
			"var endpointTable = model.NewTable(model.TableSpec{",
			"var callTable = model.NewTable(model.TableSpec{",
			"var deliveryTable = model.NewTable(model.TableSpec{",
			"var deliveryAttemptTable = model.NewTable(model.TableSpec{",
			"ManualKey: true,",
			"// arandu:begin custom\n",
			"// arandu:end custom\n",
		},
		"EndpointQuery.go":        {generatedHeading, "func Endpoints(db model.DB) *EndpointQuery", "type EndpointCollection []*Endpoint"},
		"CallQuery.go":            {generatedHeading, "func Calls(db model.DB) *CallQuery", "type CallCollection []*Call"},
		"DeliveryQuery.go":        {generatedHeading, "func Deliveries(db model.DB) *DeliveryQuery"},
		"DeliveryAttemptQuery.go": {generatedHeading, "func DeliveryAttempts(db model.DB) *DeliveryAttemptQuery"},
		"service.go": {
			"db     *database.DB",
			"Endpoints(s.db).New()",
			"Endpoints(s.db).WhereKey(",
			"Calls(s.db).WhereKey(",
			") (*Endpoint, error)",
			") ([]*Call, error)",
		},
		"module.go": {"newEndpointService(db, s)", "newCallService(db, c)"},
	}
	for path, required := range wants {
		body, err := os.ReadFile(filepath.Join(root, path))
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}
		for _, want := range required {
			if !strings.Contains(string(body), want) {
				t.Errorf("%s does not contain %q", path, want)
			}
		}
	}

	entries, err := os.ReadDir(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		body, err := os.ReadFile(filepath.Join(root, entry.Name()))
		if err != nil {
			t.Fatal(err)
		}
		for _, stale := range []string{genericModel, genericBuilder, genericRows, genericFactory, genericNewModel, genericInstance} {
			if strings.Contains(string(body), stale) {
				t.Errorf("%s spells the generic model layer %q", entry.Name(), stale)
			}
		}
		if !strings.HasSuffix(entry.Name(), "Query.go") && strings.Contains(string(body), generatedHeading) {
			t.Errorf("%s carries the heading of the generated query, which only a *Query.go file may", entry.Name())
		}
	}
}

// TestHandlersLeaveTheSubjectAndTheStatusToWhoeverRegistersThem holds the two
// things a handler of this package does not do for itself. The guard puts the
// subject on the request, so a handler reads it with ctx.User; and whoever
// registers the action turns an error into its status, so a handler returns
// the error and neither inspects it nor writes a refusal of its own. Every
// handler also hands its use case to a Service.
//
// It reads HTTPActions as syntax. Which routes sit behind the guard is held by
// calling it, in module_test.go.
func TestHandlersLeaveTheSubjectAndTheStatusToWhoeverRegistersThem(t *testing.T) {
	t.Parallel()

	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(packageRoot(t), "module.go"), nil, 0)
	if err != nil {
		t.Fatalf("parsing module.go: %v", err)
	}
	methods := map[string]*ast.FuncDecl{}
	serviceFields := map[string]bool{}
	for _, declaration := range file.Decls {
		switch declaration := declaration.(type) {
		case *ast.FuncDecl:
			if receiverType(declaration) == "Module" {
				methods[declaration.Name.Name] = declaration
			}
		case *ast.GenDecl:
			for _, specification := range declaration.Specs {
				typeSpec, ok := specification.(*ast.TypeSpec)
				if !ok || typeSpec.Name.Name != "Module" {
					continue
				}
				for _, field := range typeSpec.Type.(*ast.StructType).Fields.List {
					name := namedType(field.Type)
					if strings.HasSuffix(name, "Repository") {
						t.Errorf("Module holds %s directly; handlers reach data through a Service", name)
					}
					if strings.HasSuffix(name, "Service") {
						for _, ident := range field.Names {
							serviceFields[ident.Name] = true
						}
					}
				}
			}
		}
	}
	actions := methods["HTTPActions"]
	if actions == nil {
		t.Fatal("Module has no HTTPActions method")
	}
	if len(serviceFields) == 0 {
		t.Fatal("Module has no Service collaborator")
	}

	handlers := map[string]bool{}
	receiver := receiverName(actions)
	ast.Inspect(actions.Body, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		for _, argument := range call.Args {
			if selector, ok := argument.(*ast.SelectorExpr); ok {
				if owner, ok := selector.X.(*ast.Ident); ok && owner.Name == receiver && methods[selector.Sel.Name] != nil {
					handlers[selector.Sel.Name] = true
				}
			}
		}
		return true
	})
	if len(handlers) == 0 {
		t.Fatal("HTTPActions registers no Module handler, so this test proved nothing")
	}
	for name := range handlers {
		handler := methods[name]
		readsUser, usesService := false, false
		ast.Inspect(handler.Body, func(node ast.Node) bool {
			switch node := node.(type) {
			case *ast.SelectorExpr:
				if field, ok := node.X.(*ast.SelectorExpr); ok {
					if owner, ok := field.X.(*ast.Ident); ok && owner.Name == receiverName(handler) && serviceFields[field.Sel.Name] {
						usesService = true
					}
				}
			case *ast.CallExpr:
				switch selectorName(node.Fun) {
				case "User":
					readsUser = true
				case "Refuse", "Reject", "WriteProblem", "WriteValidationProblem":
					t.Errorf("Module.%s answers through %s by hand; return the error", name, selectorName(node.Fun))
				case "Error":
					if owner, ok := node.Fun.(*ast.SelectorExpr); ok {
						if pkg, ok := owner.X.(*ast.Ident); ok && pkg.Name == "http" {
							t.Errorf("Module.%s writes a status with http.Error; return the error", name)
						}
					}
				case "Is", "As":
					if owner, ok := node.Fun.(*ast.SelectorExpr); ok {
						if pkg, ok := owner.X.(*ast.Ident); ok && pkg.Name == "errors" {
							t.Errorf("Module.%s inspects the error to choose a status; whoever registers it does that", name)
						}
					}
				}
			}
			return true
		})
		if !readsUser {
			t.Errorf("Module.%s does not read who is asking with ctx.User", name)
		}
		if !usesService {
			t.Errorf("Module.%s does not delegate its use case to a Service", name)
		}
	}
}

// TestNothingComposesThePackageImplicitly holds that the package is wired by
// New and nothing else: no container, no provider, no registration that
// discovers what it registers.
func TestNothingComposesThePackageImplicitly(t *testing.T) {
	t.Parallel()

	forbidden := map[string]bool{
		"DiscoverProviders": true, "Providers": true, "RegisterProvider": true,
		"RegisterProviders": true, "ResolveProvider": true, "ResolveProviders": true,
	}
	for _, source := range productionGoFiles(t, packageRoot(t)) {
		for _, imported := range source.file.Imports {
			path, err := strconv.Unquote(imported.Path.Value)
			if err != nil {
				t.Fatalf("%s has an unreadable import %s", source.path, imported.Path.Value)
			}
			if strings.HasSuffix(path, "/container") || strings.Contains(path, "/container/") {
				t.Errorf("%s imports the container surface %s", source.path, path)
			}
		}
		ast.Inspect(source.file, func(node ast.Node) bool {
			switch node := node.(type) {
			case *ast.TypeSpec:
				if node.Name.Name == "Provider" || strings.HasSuffix(node.Name.Name, "ServiceProvider") {
					t.Errorf("%s declares %s, a second composition abstraction", source.path, node.Name.Name)
				}
			case *ast.FuncDecl:
				if node.Recv == nil && forbidden[node.Name.Name] {
					t.Errorf("%s declares %s, which makes registration implicit", source.path, node.Name.Name)
				}
			}
			return true
		})
	}
}

type parsedGoFile struct {
	path string
	file *ast.File
}

// productionGoFiles is every non-test Go file of the package, parsed with its
// comments, because a build constraint is one.
func productionGoFiles(t *testing.T, root string) []parsedGoFile {
	t.Helper()

	entries, err := os.ReadDir(root)
	if err != nil {
		t.Fatalf("reading %s: %v", root, err)
	}
	files := []parsedGoFile{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, ".kyse.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, name), nil, parser.ParseComments)
		if err != nil {
			t.Fatalf("parsing %s: %v", name, err)
		}
		files = append(files, parsedGoFile{path: name, file: file})
	}
	return files
}

func receiverName(function *ast.FuncDecl) string {
	if function.Recv == nil || len(function.Recv.List) == 0 || len(function.Recv.List[0].Names) == 0 {
		return ""
	}
	return function.Recv.List[0].Names[0].Name
}

func receiverType(function *ast.FuncDecl) string {
	if function.Recv == nil || len(function.Recv.List) == 0 {
		return ""
	}
	return namedType(function.Recv.List[0].Type)
}

func namedType(expression ast.Expr) string {
	switch expression := expression.(type) {
	case *ast.Ident:
		return expression.Name
	case *ast.StarExpr:
		return namedType(expression.X)
	case *ast.SelectorExpr:
		return expression.Sel.Name
	case *ast.IndexExpr:
		return namedType(expression.X)
	case *ast.IndexListExpr:
		return namedType(expression.X)
	}
	return ""
}

// packageRoot is the directory of this package.
func packageRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("finding the package directory")
	}
	return filepath.Dir(file)
}
